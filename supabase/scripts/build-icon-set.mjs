/**
 * Builds `supabase/functions/_shared/glass/icon-set.ts` from Phosphor Icons.
 *
 *   npm pack @phosphor-icons/core && tar -xzf phosphor-icons-core-*.tgz
 *   node supabase/scripts/build-icon-set.mjs <path to the unpacked package>
 *
 * The slides carry each icon's outline in their own rows, so the set is plain
 * path data — no renderer needs the package, and the phone, the web viewer,
 * the PDF and the PowerPoint file draw the same shapes. Three weights per
 * icon: `fill` (one solid shape, for gradients), `duotone` (a light body under
 * a darker outline) and `thin` (line art, for the giant outlines a Spektr
 * page carries across its colour field). Which icons, and the Uzbek and English words that call each
 * one up, are listed in `icon-catalog.json` next to this script.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = process.argv[2];
if (!root) throw new Error("usage: node build-icon-set.mjs <@phosphor-icons/core package dir>");
const pkg = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));
const catalog = JSON.parse(readFileSync(path.join(here, "icon-catalog.json"), "utf8"));

const paths = (svg) => [...svg.matchAll(/<path d="([^"]+)"(?: opacity="([0-9.]+)")?\s*\/>/g)].map((m) => ({ d: m[1], opacity: m[2] ? Number(m[2]) : 1 }));

const entries = Object.entries(catalog).map(([name, keywords]) => {
  const fill = paths(readFileSync(path.join(root, "assets/fill", `${name}-fill.svg`), "utf8"));
  const duo = paths(readFileSync(path.join(root, "assets/duotone", `${name}-duotone.svg`), "utf8"));
  const line = paths(readFileSync(path.join(root, "assets/thin", `${name}-thin.svg`), "utf8"));
  if (!fill.length || !duo.length || !line.length) throw new Error(`no paths in ${name}`);
  return `  ${JSON.stringify(name)}: { keywords: ${JSON.stringify(keywords)}, fill: ${JSON.stringify(fill.map((p) => p.d))}, duo: ${JSON.stringify(duo)}, line: ${JSON.stringify(line.map((p) => p.d))} },`;
});

const out = `/**
 * Generated by supabase/scripts/build-icon-set.mjs — do not edit by hand.
 *
 * Icon outlines from Phosphor Icons ${pkg.version} (https://phosphoricons.com),
 * MIT License, Copyright (c) 2023 Phosphor Icons. All on a 256-unit square.
 */

export type IconPath = { d: string; opacity: number };
export type IconEntry = { keywords: string[]; fill: string[]; duo: IconPath[]; line: string[] };

export const ICON_BOX = 256;

export const ICON_SET: Record<string, IconEntry> = {
${entries.join("\n")}
};
`;
writeFileSync(path.join(here, "../functions/_shared/glass/icon-set.ts"), out);
console.log(`icon-set.ts: ${entries.length} icons, ${(out.length / 1024).toFixed(0)} KB`);
