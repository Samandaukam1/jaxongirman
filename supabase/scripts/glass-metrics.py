#!/usr/bin/env python3
"""
Writes supabase/functions/_shared/glass/metrics.ts from the font files.

    python3 -m venv /tmp/fm && /tmp/fm/bin/pip install fonttools
    /tmp/fm/bin/python supabase/scripts/glass-metrics.py <dir-of-ttf> <faces.tsv> <manrope-dir>

`faces.tsv` lines are `Family|weight|storage/path.ttf`; each file is expected
in <dir-of-ttf> under the storage path with "/" replaced by "_" — which is how
the library bucket's files are fetched for this. The engine measures copy with
these advance widths, so a line breaks where the renderer will break it and
words never run into the next element.
"""
import json
import os
import sys

from fontTools.ttLib import TTFont

CHARSET = (
    " abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
    ".,:;!?‘’'\"«»“”()[]-–—%/&+№$€•·…*#@<>=_"
    # Russian, for decks written in it.
    "абвгдеёжзийклмнопрстуфхцчшщъыьэюяАБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ"
)

RUSSIAN = "абвгдеёжзийклмнопрстуфхцчшщъыьэюяАБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ"


def covers_russian(path):
    """Whether a face draws every Russian letter: only such a face may set a Russian deck."""
    cmap = TTFont(path).getBestCmap()
    return all(ord(char) in cmap for char in RUSSIAN)


def widths(path):
    font = TTFont(path)
    cmap = font.getBestCmap()
    upm = font["head"].unitsPerEm
    hmtx = font["hmtx"]
    lower = [hmtx[cmap[ord(c)]][0] for c in "abcdefghijklmnopqrstuvwxyz" if ord(c) in cmap]
    fallback = sum(lower) / max(1, len(lower))
    out = []
    for char in CHARSET:
        glyph = cmap.get(ord(char))
        advance = hmtx[glyph][0] if glyph else fallback
        out.append(min(1295, max(0, round(advance * 1000 / upm))))
    return out


def encode(values):
    digits = "0123456789abcdefghijklmnopqrstuvwxyz"
    return "".join(digits[v // 36] + digits[v % 36] for v in values)


def main():
    folder, listing, manrope = sys.argv[1], sys.argv[2], sys.argv[3]
    entries = {}
    cyrillic = set()
    for line in open(listing, encoding="utf8"):
        line = line.strip()
        if not line:
            continue
        family, weight, storage = line.split("|")
        path = os.path.join(folder, storage.replace("/", "_"))
        if os.path.exists(path):
            entries[f"{family}|{weight}"] = encode(widths(path))
            if covers_russian(path):
                cyrillic.add(family)
    for weight, name in ((400, "400Regular/Manrope_400Regular.ttf"), (500, "500Medium/Manrope_500Medium.ttf"),
                         (600, "600SemiBold/Manrope_600SemiBold.ttf"), (700, "700Bold/Manrope_700Bold.ttf")):
        entries[f"Manrope|{weight}"] = encode(widths(os.path.join(manrope, name)))
        if covers_russian(os.path.join(manrope, name)):
            cyrillic.add("Manrope")

    target = os.path.join(os.path.dirname(__file__), "../functions/_shared/glass/metrics.ts")
    with open(target, "w", encoding="utf8") as out:
        out.write("/**\n * Advance widths of every face the Liquid Glass engine sets type in.\n *\n")
        out.write(" * Generated by `supabase/scripts/glass-metrics.py` from the font files in the\n")
        out.write(" * library bucket — do not edit by hand. Each entry is the per-mille advance of\n")
        out.write(" * every character in `CHARSET`, two base-36 digits apiece. Measuring with\n")
        out.write(" * these is what lets a layout know where a line will break before any\n")
        out.write(" * renderer has drawn it.\n */\n\n")
        out.write(f"export const CHARSET = {json.dumps(CHARSET, ensure_ascii=False)};\n\n")
        out.write("export const METRICS: Record<string, string> = {\n")
        for key in sorted(entries):
            out.write(f'  "{key}": "{entries[key]}",\n')
        out.write("};\n\n")
        out.write("/** Families that draw every Russian letter: a Russian deck is set only in these. */\n")
        out.write(f"export const CYRILLIC_FAMILIES: ReadonlySet<string> = new Set({json.dumps(sorted(cyrillic), ensure_ascii=False)});\n")
    print(f"{len(entries)} faces -> {os.path.normpath(target)}")


if __name__ == "__main__":
    main()
